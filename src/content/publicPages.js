export function getPublicPageByPath(pathname) {
  const rawPath = String(pathname || "/");
  const normalizedPath = rawPath === "/" ? "/" : rawPath.replace(/\/+$/, "");
  return PUBLIC_PAGE_LIST.find((page) => page.path === normalizedPath) || null;
}

export function getPublicPageBySlug(slug) {
  return PUBLIC_PAGE_LIST.find((page) => page.slug === String(slug || "")) || null;
}
